let repoWriteMutex: Promise<unknown> = Promise.resolve();

function withWriteLock<T>(task: () => Promise<T>): Promise<T> {
  const next = repoWriteMutex.then(task, task);
  repoWriteMutex = next.then(
    () => undefined,
    () => undefined
  );
  return next;
}

